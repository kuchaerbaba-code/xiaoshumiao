create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, nickname, family_name, terms_version, privacy_version, guardian_consent_at)
  values (
    new.id,
    new.email,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1), '家长'),
    coalesce(nullif(new.raw_user_meta_data ->> 'family', ''), '我的家庭'),
    nullif(new.raw_user_meta_data ->> 'terms_version', ''),
    nullif(new.raw_user_meta_data ->> 'privacy_version', ''),
    case when new.raw_user_meta_data ->> 'guardian_consent' = 'true' then now() else null end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

