create or replace function public.accept_family_invitation(p_invite_code text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_invite public.family_invitations%rowtype;
  v_existing uuid;
begin
  if v_user is null then raise exception '请先登录'; end if;

  select * into v_invite
  from public.family_invitations
  where invite_code = upper(trim(p_invite_code)) and status = 'pending'
  limit 1;

  if v_invite.id is null then raise exception '邀请链接无效或已使用'; end if;
  if v_invite.expires_at < now() then
    update public.family_invitations set status = 'expired' where id = v_invite.id;
    raise exception '邀请链接已过期，请让家长重新邀请';
  end if;
  if lower(v_invite.invited_email) <> v_email then
    raise exception '请使用被邀请的邮箱登录';
  end if;

  select family_id into v_existing
  from public.family_members where user_id = v_user and status = 'active' limit 1;

  if v_existing is not null and v_existing <> v_invite.family_id then
    if exists (
      select 1 from public.family_members
      where family_id = v_existing and status = 'active' and user_id <> v_user
    ) or exists (
      select 1 from public.family_states
      where family_id = v_existing
        and (
          jsonb_array_length(coalesce(data -> 'children', '[]'::jsonb)) > 0
          or jsonb_array_length(coalesce(data -> 'records', '[]'::jsonb)) > 0
        )
    ) then
      raise exception '该账号已有家庭成长数据，不能直接加入另一家庭';
    end if;
    delete from public.family_members where family_id = v_existing and user_id = v_user;
    delete from public.families where id = v_existing and owner_id = v_user;
  end if;

  insert into public.family_members (family_id, user_id, role, status)
  values (v_invite.family_id, v_user, 'parent', 'active')
  on conflict (family_id, user_id) do update set status = 'active';

  update public.family_invitations
  set status = 'accepted', accepted_by = v_user, accepted_at = now()
  where id = v_invite.id;

  return v_invite.family_id;
end;
$$;

