-- 仅由已验签且已核验金额的微信支付回调调用。重复回调会安全地返回已确认状态。
create or replace function public.confirm_wechat_gallery_payment(
  p_out_trade_no text,
  p_transaction_id text,
  p_amount numeric,
  p_paid_at timestamptz default now()
)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  v_recharge public.gallery_recharges%rowtype;
begin
  select * into v_recharge
  from public.gallery_recharges
  where out_trade_no = p_out_trade_no
  for update;

  if v_recharge.id is null then
    raise exception 'Payment order not found';
  end if;
  if v_recharge.provider <> 'wechatpay' then
    raise exception 'Payment provider mismatch';
  end if;
  if v_recharge.amount <> p_amount then
    raise exception 'Payment amount mismatch';
  end if;
  if v_recharge.status = 'approved' then
    if v_recharge.transaction_id is not null and v_recharge.transaction_id <> p_transaction_id then
      raise exception 'Payment transaction mismatch';
    end if;
    return jsonb_build_object('status', 'approved', 'recharge_id', v_recharge.id, 'duplicate', true);
  end if;

  update public.gallery_recharges
  set status = 'approved', transaction_id = p_transaction_id, paid_at = p_paid_at, approved_at = now()
  where id = v_recharge.id;

  update public.profiles
  set
    gallery_unlocked = true,
    gallery_plan = case when gallery_plan = '10gb' then '10gb' else v_recharge.requested_plan end,
    gallery_unlocked_at = now(),
    updated_at = now()
  where id = v_recharge.user_id;

  return jsonb_build_object('status', 'approved', 'recharge_id', v_recharge.id, 'duplicate', false);
end;
$$;

revoke all on function public.confirm_wechat_gallery_payment(text, text, numeric, timestamptz) from public;
revoke all on function public.confirm_wechat_gallery_payment(text, text, numeric, timestamptz) from authenticated;
grant execute on function public.confirm_wechat_gallery_payment(text, text, numeric, timestamptz) to service_role;

