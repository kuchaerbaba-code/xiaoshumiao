create or replace function public.claim_daily_login()
returns public.profiles
language plpgsql
security definer set search_path = public
as $$
declare
  v_today date := (timezone('Asia/Shanghai', now()))::date;
  v_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  insert into public.profiles (id, email, nickname, family_name, terms_version, privacy_version, guardian_consent_at)
  select
    u.id,
    u.email,
    coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(u.email, '@', 1), '家长'),
    coalesce(nullif(u.raw_user_meta_data ->> 'family', ''), '我的家庭'),
    nullif(u.raw_user_meta_data ->> 'terms_version', ''),
    nullif(u.raw_user_meta_data ->> 'privacy_version', ''),
    case when u.raw_user_meta_data ->> 'guardian_consent' = 'true' then u.created_at else null end
  from auth.users u
  where u.id = auth.uid()
  on conflict (id) do nothing;

  update public.profiles
  set
    exp = exp + case when last_login_date is distinct from v_today then 10 else 0 end,
    last_login_date = v_today,
    updated_at = now()
  where id = auth.uid()
  returning * into v_profile;

  return v_profile;
end;
$$;

revoke all on function public.claim_daily_login() from public;
grant execute on function public.claim_daily_login() to authenticated;

