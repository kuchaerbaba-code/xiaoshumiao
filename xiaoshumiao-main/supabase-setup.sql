create or replace function public.approve_gallery_recharge(p_recharge_id bigint)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_user_id uuid;
  v_plan text;
begin
  update public.gallery_recharges
  set status = 'approved', approved_at = now()
  where id = p_recharge_id and status = 'pending'
  returning user_id, requested_plan into v_user_id, v_plan;

